CREATE TABLE public."comments" (
	id int4 GENERATED BY DEFAULT AS IDENTITY( INCREMENT BY 1 MINVALUE 1 MAXVALUE 2147483647 START 1 CACHE 1 NO CYCLE) NOT NULL,
	commented_by_id int4 NOT NULL,
	"comment" text NULL,
	under_post_id int4 NOT NULL,
	"timestamp" timestamptz NOT NULL,
	CONSTRAINT comments_commented_by_not_null NOT NULL commented_by_id,
	CONSTRAINT comments_id PRIMARY KEY (id),
	CONSTRAINT comments_id_not_null NOT NULL id,
	CONSTRAINT comments_timestamp_not_null NOT NULL "timestamp",
	CONSTRAINT comments_under_post_not_null NOT NULL under_post_id
);