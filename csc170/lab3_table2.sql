CREATE TABLE public.posts (
	id int4 GENERATED BY DEFAULT AS IDENTITY NOT NULL,
	posted_by_id int4 NOT NULL,
	post text NULL,
	"timestamp" timestamp NOT NULL,
	CONSTRAINT posts_id PRIMARY KEY (id),
	CONSTRAINT posts_id_not_null NOT NULL id,
	CONSTRAINT posts_posted_by_not_null NOT NULL posted_by_id,
	CONSTRAINT posts_timestamp_not_null NOT NULL "timestamp"
);